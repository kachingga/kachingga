import '@testing-library/jest-dom/vitest';

import { cleanup } from '@testing-library/react';
import { afterEach } from 'vitest';

afterEach(() => cleanup());

// The app formats in the browser's language; tests run as a browser in Argentina.
Object.defineProperty(window.navigator, 'language', { value: 'es-AR', configurable: true });

// jsdom has no matchMedia (the toasts use it to follow the system theme).
window.matchMedia ??= (query: string) =>
  ({
    matches: false,
    media: query,
    onchange: null,
    addEventListener: () => {},
    removeEventListener: () => {},
    addListener: () => {},
    removeListener: () => {},
    dispatchEvent: () => false,
  }) as MediaQueryList;

// Nor pointer capture (the toasts use it when tapping their buttons).
Element.prototype.setPointerCapture ??= () => {};
Element.prototype.releasePointerCapture ??= () => {};
Element.prototype.hasPointerCapture ??= () => false;
